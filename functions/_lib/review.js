/* Shared review state for one answer, and the operations that change it.

   The generated answer itself lives in static data and is never modified.
   Version 1 is always that original; every later version is a reviewer
   action (a batch of fixes, an edit, or a roll-back), so nothing a reviewer
   does can lose the original or any earlier edit.

   state = {
     version, seq,
     versions: [{version, kind: generated|fix|edit|rollback, change, by, date, flag_ids, text|null, original?, rolled_back_to?}],
       original: true = the generated answer's text; otherwise text null = same text as the version before
     flags: [{id, title, description, proposed_fix, suggested_text, category, severity, anchor,
              status: open|fixed, opened_by, opened_date, fixed_by?, fixed_date?, fixed_in_version?}],
     comments: {flag_id: [{who, date, text}]},
     bin: [{flag, comments, deleted_by, deleted_date}],
     human_levels: {rubric_key: {level, note, by, date}},
   } */

export const RUBRIC_MAX = { reasoning: 4, user_data: 4, research: 4, missing_info: 3, intent: 4 };
const SEVERITIES = ["High", "Medium", "Low"];

export class OpError extends Error {}

export function emptyState() {
  return {
    version: 1,
    seq: 0,
    versions: [{ version: 1, kind: "generated", change: "Answer as generated by the pipeline", by: "pipeline", date: null, flag_ids: [], text: null, original: true }],
    flags: [],
    comments: {},
    bin: [],
    human_levels: {},
  };
}

function str(v, max, field, required = false) {
  const s = v == null ? "" : String(v).trim();
  if (required && !s) throw new OpError(`${field} is required`);
  if (s.length > max) throw new OpError(`${field} is too long (max ${max} characters)`);
  return s;
}

function cleanAnchor(a) {
  if (!a || typeof a !== "object") return undefined;
  const out = { key: str(a.key, 200, "anchor.key", true), label: str(a.label, 200, "anchor.label") || a.key };
  if (a.quote) out.quote = str(a.quote, 2000, "anchor.quote");
  if (a.context) out.context = str(a.context, 4000, "anchor.context");
  if (Number.isInteger(a.version)) out.version = a.version;
  return out;
}

function findFlag(state, id) {
  const f = state.flags.find(x => x.id === id);
  if (!f) throw new OpError("That flag no longer exists — someone may have deleted it. Refresh to see the latest.");
  return f;
}

/* Answer text as of a version (null = the original generated text). */
export function textAt(state, version) {
  for (let i = state.versions.length - 1; i >= 0; i--) {
    const v = state.versions[i];
    if (v.version > version) continue;
    if (v.original) return null;
    if (v.text != null) return v.text;
  }
  return null;
}

function bump(state, entry) {
  state.version += 1;
  state.versions.push({ version: state.version, ...entry });
  return state.version;
}

function markFixed(state, ids, who, now, version) {
  ids.forEach(id => {
    const f = findFlag(state, id);
    if (f.status === "fixed") return;
    Object.assign(f, { status: "fixed", fixed_by: who, fixed_date: now, fixed_in_version: version });
  });
}

export function applyOp(state, op, who, now = new Date().toISOString()) {
  if (!op || typeof op.op !== "string") throw new OpError("Missing op");
  switch (op.op) {
    case "add_flag": {
      const severity = SEVERITIES.includes(op.severity) ? op.severity : "Medium";
      const flag = {
        id: `f${++state.seq}`,
        title: str(op.title, 200, "Title", true),
        description: str(op.description, 4000, "Details"),
        proposed_fix: str(op.proposed_fix, 4000, "Proposed fix"),
        suggested_text: str(op.suggested_text, 20000, "Suggested rewrite"),
        category: str(op.category, 80, "Category"),
        severity,
        anchor: cleanAnchor(op.anchor),
        status: "open",
        opened_by: who,
        opened_date: now,
      };
      state.flags.push(flag);
      return { flag_id: flag.id };
    }
    case "add_comment": {
      findFlag(state, op.flag_id);
      (state.comments[op.flag_id] = state.comments[op.flag_id] || []).push({ who, date: now, text: str(op.text, 4000, "Comment", true) });
      return {};
    }
    case "fix_flags": {
      const ids = [...new Set(op.flag_ids || [])];
      const open = ids.filter(id => findFlag(state, id).status !== "fixed");
      if (!open.length) throw new OpError("Nothing to mark fixed");
      const note = str(op.note, 500, "Note");
      const v = bump(state, { kind: "fix", change: note || `Marked ${open.length} flag${open.length === 1 ? "" : "s"} fixed`, by: who, date: now, flag_ids: open, text: null });
      markFixed(state, open, who, now, v);
      return { version: v };
    }
    case "save_edit": {
      const text = str(op.text, 50000, "Answer text", true);
      if (textAt(state, state.version) === text) throw new OpError("The answer is unchanged");
      const ids = [...new Set(op.flag_ids || [])].filter(id => findFlag(state, id).status !== "fixed");
      const change = str(op.change, 500, "Summary of the change") || "Edited the answer";
      const v = bump(state, { kind: "edit", change, by: who, date: now, flag_ids: ids, text });
      markFixed(state, ids, who, now, v);
      return { version: v };
    }
    case "revert_to_version": {
      const target = Number(op.version);
      if (!state.versions.some(v => v.version === target) || target >= state.version) throw new OpError("Pick an earlier version");
      const reopened = state.flags.filter(f => f.status === "fixed" && f.fixed_in_version > target);
      reopened.forEach(f => {
        f.status = "open";
        delete f.fixed_by; delete f.fixed_date; delete f.fixed_in_version;
      });
      // Non-destructive: later versions stay in the history; this adds a new one with v<target>'s text.
      const text = textAt(state, target);
      const v = bump(state, {
        kind: "rollback", change: `Rolled back to v${target}`, by: who, date: now,
        flag_ids: reopened.map(f => f.id), text, original: text == null, rolled_back_to: target,
      });
      return { version: v, reopened: reopened.length };
    }
    case "delete_flag": {
      const f = findFlag(state, op.flag_id);
      if (f.status === "fixed") throw new OpError("Fixed flags are part of the version history and can't be deleted");
      state.flags = state.flags.filter(x => x.id !== f.id);
      state.bin.push({ flag: f, comments: state.comments[f.id] || [], deleted_by: who, deleted_date: now });
      delete state.comments[f.id];
      return {};
    }
    case "restore_flag": {
      const i = state.bin.findIndex(b => b.flag.id === op.flag_id);
      if (i < 0) throw new OpError("That flag isn't in the bin");
      const [entry] = state.bin.splice(i, 1);
      state.flags.push(entry.flag);
      if (entry.comments.length) state.comments[entry.flag.id] = entry.comments;
      return {};
    }
    case "purge_flag": {
      const before = state.bin.length;
      state.bin = state.bin.filter(b => b.flag.id !== op.flag_id);
      if (state.bin.length === before) throw new OpError("That flag isn't in the bin");
      return {};
    }
    case "set_human_level": {
      const max = RUBRIC_MAX[op.rubric];
      if (!max) throw new OpError("Unknown rubric");
      if (op.level == null) { delete state.human_levels[op.rubric]; return {}; }
      const level = Number(op.level);
      if (!Number.isInteger(level) || level < 1 || level > max) throw new OpError(`Level must be 1–${max}`);
      state.human_levels[op.rubric] = { level, note: str(op.note, 2000, "Note"), by: who, date: now };
      return {};
    }
    default:
      throw new OpError(`Unknown op: ${op.op}`);
  }
}
