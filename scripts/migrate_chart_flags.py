"""Move Chart QA's patient flags into this portal's database.

Chart QA keeps one row per patient in its own D1 (`patient_state`, plus the
`review_events` audit trail). This portal keeps one row per *reviewed thing*
in `review_state`, where a patient profile is the id `patient-<n>`. Both
already store flags, comments, a bin and a version history — the shapes are
close, but not the same, and this portal may already hold profile flags of its
own that must not be lost.

    # 1. export from Chart QA
    wrangler d1 execute patient-review --remote --json \
      --command "SELECT patient_id, state, rev, updated_at, updated_by FROM patient_state" > chart_state.json
    wrangler d1 execute patient-review --remote --json \
      --command "SELECT id, patient_id, op, payload, email, at FROM review_events ORDER BY id" > chart_events.json

    # 2. export what this portal already has, so nothing is clobbered
    wrangler d1 execute answer-review --remote --json \
      --command "SELECT answer_id, state, rev FROM review_state WHERE answer_id LIKE 'patient-%'" > answer_state.json

    # 3. see what would happen
    python scripts/migrate_chart_flags.py --chart chart_state.json --events chart_events.json \
        --existing answer_state.json --dry-run

    # 4. write the SQL, read it, then apply it
    python scripts/migrate_chart_flags.py --chart chart_state.json --events chart_events.json \
        --existing answer_state.json --out migrate.sql
    wrangler d1 execute answer-review --remote --file=migrate.sql

Nothing is deleted. Chart QA's database is only read; this writes SQL for this
portal's database and leaves applying it to you.

What the conversion has to deal with:

  flag ids       Chart QA mints "f" + a timestamp; this portal mints f1, f2…
                 from a per-row `seq`. Both can appear in the same row after a
                 merge, so incoming flags are renumbered above the existing
                 `seq`, and every reference to them — comments, bin entries,
                 version_history.flag_ids — is remapped with them.
  fixed flags    This portal records `fixed_in_version` so a roll-back knows
                 what to reopen. Chart QA doesn't, so it is recovered from the
                 version history entry whose flag_ids contain the flag.
  versions       Chart QA's history starts at v2 and assumes v1; this portal
                 wants an explicit v1 "generated" entry, so one is synthesised.
  dates          Chart QA stores a date ("2026-10-02"), this portal an ISO
                 timestamp. Dates are carried across unchanged rather than
                 padded with a fabricated time.
  severity       Chart QA allows High/Medium/Low, same as here. Anything else
                 becomes Medium, matching what applyOp would do.
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SEVERITIES = {"High", "Medium", "Low"}


def load_d1(path):
    """wrangler --json wraps results as [{"results": [...]}, ...]; accept a bare list too."""
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    if isinstance(data, dict):
        data = [data]
    rows = []
    for block in data:
        if isinstance(block, dict) and "results" in block:
            rows += block["results"]
        elif isinstance(block, dict):
            rows.append(block)
    return rows


def patient_numbers():
    """Chart QA's patient id ("ckd") -> this portal's number, via the folder name."""
    path = os.path.join(ROOT, "profile_source", "chart_qa", "patients.json")
    if not os.path.exists(path):
        sys.exit(f"Need {path}. Run scripts/sync_chart_data.py first.")
    out = {}
    for p in json.load(open(path, encoding="utf-8")):
        m = re.match(r"\s*(\d+)", p["folder"])
        if m:
            out[p["id"]] = int(m.group(1))
    return out


def empty_state():
    """Mirrors emptyState() in functions/_lib/review.js."""
    return {
        "version": 1,
        "seq": 0,
        "versions": [{"version": 1, "kind": "generated", "change": "Answer as generated by the pipeline",
                      "by": "pipeline", "date": None, "flag_ids": [], "text": None, "original": True}],
        "flags": [], "comments": {}, "bin": [], "human_levels": {},
    }


def convert_flag(f, new_id, fixed_in):
    """Chart QA's flag -> this portal's, which is a superset."""
    out = {
        "id": new_id,
        "title": f.get("title", ""),
        "description": f.get("description", "") or "",
        "proposed_fix": f.get("proposed_fix", "") or "",
        "suggested_text": "",          # Chart QA has no equivalent
        "category": f.get("type", "") or "",   # its flag-type tag, if present
        "severity": f.get("severity") if f.get("severity") in SEVERITIES else "Medium",
        "status": "fixed" if f.get("status") == "fixed" else "open",
        "opened_by": f.get("opened_by", "") or "",
        "opened_date": f.get("opened_date", "") or "",
    }
    if f.get("anchor"):
        out["anchor"] = f["anchor"]
    if out["status"] == "fixed":
        out["fixed_by"] = f.get("fixed_by", "") or ""
        out["fixed_date"] = f.get("fixed_date", "") or ""
        if fixed_in:
            out["fixed_in_version"] = fixed_in
    return out


def merge(chart_state, target):
    """Fold one Chart QA patient row into this portal's state for that patient."""
    base_seq = target["seq"]
    # Renumber every incoming flag above the existing seq, keeping a map so
    # comments, bin entries and version_history flag_ids follow.
    remap, seq = {}, base_seq
    for f in chart_state.get("flags", []):
        seq += 1
        remap[f["id"]] = f"f{seq}"
    for entry in chart_state.get("bin", []):
        fid = (entry.get("flag") or {}).get("id")
        if fid and fid not in remap:
            seq += 1
            remap[fid] = f"f{seq}"

    # Which version fixed each flag, so roll-back can reopen the right ones.
    base_version = target["version"]
    fixed_in = {}
    for v in chart_state.get("version_history", []):
        for fid in v.get("flag_ids", []):
            # Chart QA's v2 becomes this row's next version after what's here.
            fixed_in[fid] = base_version + max(1, v["version"] - 1)

    for f in chart_state.get("flags", []):
        target["flags"].append(convert_flag(f, remap[f["id"]], fixed_in.get(f["id"])))

    for old_id, comments in (chart_state.get("comments") or {}).items():
        if old_id in remap and comments:
            target["comments"].setdefault(remap[old_id], []).extend(comments)

    for entry in chart_state.get("bin", []):
        f = entry.get("flag") or {}
        if not f.get("id"):
            continue
        target["bin"].append({
            "flag": convert_flag(f, remap[f["id"]], None),
            "comments": entry.get("comments", []) or [],
            "deleted_by": entry.get("deleted_by", "") or "",
            "deleted_date": entry.get("deleted_date", "") or "",
        })

    # Chart QA's history assumes v1 is the profile as generated; this portal
    # already has its own v1, so each imported batch becomes a new version here.
    for v in sorted(chart_state.get("version_history", []), key=lambda x: x["version"]):
        target["version"] += 1
        target["versions"].append({
            "version": target["version"],
            "kind": "fix",
            "change": v.get("change", "") or f"Imported from Chart QA v{v['version']}",
            "by": v.get("by", "") or "",
            "date": v.get("date"),
            "flag_ids": [remap[i] for i in v.get("flag_ids", []) if i in remap],
            "text": None,
        })

    target["seq"] = seq
    return target, remap


def sql_str(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--chart", required=True, help="patient_state export from Chart QA")
    ap.add_argument("--events", help="review_events export from Chart QA (optional)")
    ap.add_argument("--existing", help="this portal's current patient-% rows, so they're merged not replaced")
    ap.add_argument("--out", help="write SQL here (default: stdout with --dry-run off)")
    ap.add_argument("--dry-run", action="store_true", help="summarise, write nothing")
    args = ap.parse_args()

    numbers = patient_numbers()
    chart_rows = load_d1(args.chart)
    existing = {}
    if args.existing:
        for r in load_d1(args.existing):
            try:
                existing[r["answer_id"]] = {"state": json.loads(r["state"]), "rev": r.get("rev", 0)}
            except (json.JSONDecodeError, TypeError):
                sys.exit(f"Could not parse existing state for {r.get('answer_id')!r}")

    statements, summary, skipped = [], [], []
    for row in chart_rows:
        pid = row.get("patient_id")
        n = numbers.get(pid)
        if n is None:
            skipped.append(pid)
            continue
        try:
            chart_state = json.loads(row["state"])
        except (json.JSONDecodeError, TypeError):
            skipped.append(f"{pid} (unparseable state)")
            continue

        answer_id = f"patient-{n}"
        prior = existing.get(answer_id)
        target = prior["state"] if prior else empty_state()
        before = len(target.get("flags", []))
        target, remap = merge(chart_state, target)

        body = json.dumps(target, ensure_ascii=False, separators=(",", ":"))
        who = row.get("updated_by") or "chart-qa-migration"
        when = row.get("updated_at") or ""
        if prior:
            # Guard on rev: if someone edits this profile between the export and
            # the apply, the UPDATE matches nothing and that patient is skipped
            # rather than silently overwriting their work.
            statements.append(
                f"UPDATE review_state SET state = {sql_str(body)}, rev = rev + 1, "
                f"updated_at = {sql_str(when)}, updated_by = {sql_str(who)} "
                f"WHERE answer_id = {sql_str(answer_id)} AND rev = {int(prior['rev'])};")
        else:
            statements.append(
                f"INSERT INTO review_state (answer_id, state, rev, updated_at, updated_by) "
                f"VALUES ({sql_str(answer_id)}, {sql_str(body)}, 1, {sql_str(when)}, {sql_str(who)}) "
                f"ON CONFLICT(answer_id) DO NOTHING;")

        summary.append({
            "chart_id": pid, "answer_id": answer_id,
            "flags_in": len(chart_state.get("flags", [])),
            "flags_before": before, "flags_after": len(target["flags"]),
            "binned": len(chart_state.get("bin", []) or []),
            "comments": sum(len(v) for v in (chart_state.get("comments") or {}).values()),
            "versions_added": len(chart_state.get("version_history", []) or []),
            "renumbered": sum(1 for k, v in remap.items() if k != v),
            "mode": "merge" if prior else "insert",
        })

    event_count = 0
    if args.events:
        events = load_d1(args.events)
        for e in events:
            n = numbers.get(e.get("patient_id"))
            if n is None:
                continue
            statements.append(
                "INSERT INTO review_events (answer_id, op, payload, email, at) VALUES ("
                f"{sql_str(f'patient-{n}')}, {sql_str(e.get('op', ''))}, {sql_str(e.get('payload', '{}'))}, "
                f"{sql_str(e.get('email', ''))}, {sql_str(e.get('at', ''))});")
            event_count += 1

    print(f"{len(summary)} patient row(s) to migrate"
          + (f", {event_count} audit event(s)" if args.events else ""))
    for s in summary:
        print(f"  {s['chart_id']:<20} -> {s['answer_id']:<12} {s['mode']:<6} "
              f"flags {s['flags_before']}+{s['flags_in']}={s['flags_after']}"
              + (f"  renumbered {s['renumbered']}" if s["renumbered"] else "")
              + (f"  bin {s['binned']}" if s["binned"] else "")
              + (f"  comments {s['comments']}" if s["comments"] else "")
              + (f"  +{s['versions_added']} version(s)" if s["versions_added"] else ""))
    if skipped:
        print(f"\n  skipped (no matching patient number): {', '.join(map(str, skipped))}")

    if args.dry_run:
        print(f"\nDry run — {len(statements)} statement(s) not written.")
        return

    sql = ("-- Chart QA flags -> this portal's review_state.\n"
           "-- Generated by scripts/migrate_chart_flags.py. Read before applying.\n"
           "-- Re-applying this file would duplicate flags: run it once.\n\n"
           + "\n".join(statements) + "\n")
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(sql)
        print(f"\nWrote {len(statements)} statement(s) to {args.out}")
        print("Read it, then: wrangler d1 execute answer-review --remote --file=" + args.out)
    else:
        print()
        print(sql)


if __name__ == "__main__":
    main()
